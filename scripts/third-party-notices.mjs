// Since 0.9.1 the published package bundles its runtime dependencies into
// dist/ (so `npx -y sniff-qa --mcp` downloads one small tarball and answers
// the MCP handshake in seconds). Their licenses must travel with them: this
// reads the esbuild metafile that `tsup` writes, lists every bundled package,
// and writes THIRD-PARTY-NOTICES.md with each package's license text.
// The browser engine (Playwright, axe-core, Lighthouse, chrome-launcher) is
// not bundled; sniff downloads it on demand with npm, licenses included.
import { existsSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const META = join(ROOT, "dist", "metafile-esm.json");
const OUT = join(ROOT, "THIRD-PARTY-NOTICES.md");

if (!existsSync(META)) {
  console.error("dist/metafile-esm.json is missing: run tsup first");
  process.exit(1);
}
const meta = JSON.parse(readFileSync(META, "utf8"));

// "node_modules/@scope/name/..." or "node_modules/name/..." (nested too).
const pkgDirs = new Set();
for (const input of Object.keys(meta.inputs)) {
  const m = input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
  if (m) pkgDirs.add(m[1]);
}

const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt|markdown))?$/i;
const entries = [];
for (const dir of pkgDirs) {
  const pkg = JSON.parse(readFileSync(join(ROOT, dir, "package.json"), "utf8"));
  const files = readdirSync(join(ROOT, dir)).filter((f) => LICENSE_FILE.test(f)).sort();
  const texts = files.map((f) => readFileSync(join(ROOT, dir, f), "utf8").trim());
  const license = typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? "see text";
  entries.push({ name: pkg.name, version: pkg.version, license, texts });
}
// One entry per name@version, sorted, so the file is stable between builds.
const seen = new Set();
const unique = entries
  .filter((e) => (seen.has(`${e.name}@${e.version}`) ? false : seen.add(`${e.name}@${e.version}`)))
  .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const missing = unique.filter((e) => e.texts.length === 0);
const lines = [
  "# Third-party notices",
  "",
  "The sniff-qa package bundles the open source packages below into `dist/`.",
  "Each keeps its own license, reproduced here. Generated by `scripts/third-party-notices.mjs`",
  "during `npm run build`; do not edit by hand.",
  "",
  `${unique.length} packages.`,
  "",
];
for (const e of unique) {
  lines.push(`## ${e.name}@${e.version}`, "", `License: ${e.license}`, "");
  for (const t of e.texts) lines.push("```text", t.replace(/```/g, "'''"), "```", "");
  if (e.texts.length === 0) lines.push(`No license file ships in the package; its package.json declares ${e.license}.`, "");
}
writeFileSync(OUT, lines.join("\n"));
rmSync(META);
console.log(`THIRD-PARTY-NOTICES.md: ${unique.length} bundled packages, ${missing.length} without a license file`);
if (missing.length) console.log(`  without a file: ${missing.map((e) => `${e.name} (${e.license})`).join(", ")}`);
